# === تحليل التقييم الائتماني ===
def analyze_credit_rating(score):
    """
    تحليل درجة الائتمان وإرجاع التصنيف المناسب
    
    Args:
        score: درجة الائتمان (رقم)
        
    Returns:
        قاموس يحتوي على التصنيف والقرار واللون
    """
    if not score or score == 0:
        return {
            "rating": "لا يوجد سجل",
            "decision": "لا يوجد سجل ائتماني",
            "color": "#95a5a6",
            "class": "rating-default"
        }
    elif 751 <= score <= 850:
        return {
            "rating": "جدارة فائقة",
            "decision": "آمن ائتمانيًا",
            "color": "#27ae60",
            "class": "rating-excellent"
        }
    elif 701 <= score <= 750:
        return {
            "rating": "جدارة قوية",
            "decision": "ملتزم",
            "color": "#2ecc71",
            "class": "rating-verygood"
        }
    elif 626 <= score <= 700:
        return {
            "rating": "جدارة مقبولة",
            "decision": "قد يتطلب ضمانات",
            "color": "#f39c12",
            "class": "rating-good"
        }
    elif 521 <= score <= 625:
        return {
            "rating": "مخاطر متوسطة",
            "decision": "حذر",
            "color": "#e67e22",
            "class": "rating-poor"
        }
    elif 400 <= score <= 520:
        return {
            "rating": "مخاطر مرتفعة",
            "decision": "رفض محتمل",
            "color": "#e74c3c",
            "class": "rating-high-risk"
        }
    else:
        return {
            "rating": "مخاطر جداً",
            "decision": "رفض",
            "color": "#e74c3c",
            "class": "rating-high-risk"
        }